    const imgherofadeItems = wrapper.querySelectorAll("[anime-hero-image-fade]");
    if (imgherofadeItems.length) {
        tl.to(imgherofadeItems, {
            y: 0,
            duration: 1.25 * mobileDurationMultiplier,
            ease: "power2.out",
