                const fadeItems = wrapper.querySelectorAll("[data-anime-fade]");
                if (fadeItems.length) {
                    tl.to(fadeItems, {
                        opacity: 1,
                        y: 0,
                        duration: isMobile ? 0.5 : 0.7,
                        ease: "power2.out",
                        stagger: 0.05 * mobileStaggerMultiplier
