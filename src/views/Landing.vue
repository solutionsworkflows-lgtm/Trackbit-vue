// Função auxiliar para animações de linha
function animateLineEffects(container, timeline, isMobile) {
    // Height animations
    const heightItems = container.querySelectorAll("[data-line-anime-height], [data-hero-line-anime-height]");
    heightItems.forEach((item) => {
        const targetHeight = item.getAttribute("data-line-anime-height") ||
            item.getAttribute("data-hero-line-anime-height") || "100%";
        timeline.to(item, {
            height: targetHeight,
            duration: isMobile ? 1.5 : 2.5,
            delay: "random(0, 0.5)",
            ease: "power2.out"
        }, 0);
    });

    // Width animations
    const widthItems = container.querySelectorAll("[data-line-anime-width], [data-hero-line-anime-width]");
    widthItems.forEach((item) => {
        const targetWidth = item.getAttribute("data-line-anime-width") ||
            item.getAttribute("data-hero-line-anime-width") || "100%";
        timeline.to(item, {
            width: targetWidth,
            duration: isMobile ? 1.5 : 2.5,
            delay: "random(0, 0.5)",
            ease: "power2.out"
        }, 0);
    });

    // Divider width animations
    const dividerwidthItems = container.querySelectorAll("[data-line-anime-width-divider]");
    dividerwidthItems.forEach((item) => {
        const dividertargetWidth = item.getAttribute("data-line-anime-width-divider") || "100%";
        timeline.to(item, {
            width: dividertargetWidth,
            duration: isMobile ? 1.5 : 2.5,
            ease: "power2.out",
            stagger: 0.1
        }, 0.3);
    });
}


