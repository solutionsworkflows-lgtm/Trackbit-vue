        tl.to(herofadeItems, {
            opacity: 1,
            y: 0,
            duration: 1.25 * mobileDurationMultiplier,
            ease: "power2.out",
            stagger: 0.1 * mobileStaggerMultiplier
        }, 0.15);
    }

