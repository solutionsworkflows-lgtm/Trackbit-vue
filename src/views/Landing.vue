                if (fadefastItems.length) {
                    tl.to(fadefastItems, {
                        opacity: 1,
                        y: 0,
                        duration: 0.3,
                        ease: "power2.out",
                        stagger: 0.025 * mobileStaggerMultiplier
                    }, 0.2);
