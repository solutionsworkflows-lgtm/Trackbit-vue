// Animação das seções de cartão
function animateCardSections(isMobile) {
    const wrappers = document.querySelectorAll("[data-header-card-anime]");
    const mobileStaggerMultiplier = isMobile ? 0.5 : 1;

    wrappers.forEach((wrapper) => {
        ScrollTrigger.create({
            trigger: wrapper,
            start: isMobile ? "top 85%" : "top 70%",
            once: true,
            onEnter: () => {
                const tl = gsap.timeline();

                // Blur animation
                const blurItems = wrapper.querySelectorAll("[data-blur-anime]");
                if (blurItems.length) {
                    tl.to(blurItems, {
                        filter: "blur(0px)",
                        opacity: 1,
                        duration: 0.4,
                        ease: "power2.out"
                    }, 0);
                }

                // Opacity animation
                const opacityItems = wrapper.querySelectorAll("[data-anime-opacity]");
                if (opacityItems.length) {
                    tl.to(opacityItems, {
                        opacity: 1,
                        duration: isMobile ? 0.7 : 1.25,
                        ease: "none"
                    }, 0.1);
                }

