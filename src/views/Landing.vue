                if (opacitynowItems.length) {
                    tl.to(opacitynowItems, {
                        opacity: 1,
                        duration: 0.05,
                        ease: "none"
                    }, 0.15);
                }

                // Staggered opacity
                const stageropacityItems = wrapper.querySelectorAll("[data-anime-opacity-stager]");
                if (stageropacityItems.length) {
                    tl.to(stageropacityItems, {
                        opacity: 1,
                        duration: isMobile ? 0.7 : 1.25,
                        ease: "none",
                        stagger: 0.1 * mobileStaggerMultiplier
                    }, 0.1);
                }

