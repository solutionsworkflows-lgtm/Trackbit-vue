                    tl.to(fadelumiItems, {
                        opacity: 1,
                        force3D: false,
                        duration: isMobile ? 0.5 : 0.7,
                        ease: "power2.out",
                        stagger: 0.05 * mobileStaggerMultiplier
                    }, 0.2);
