// Animação da seção hero
function animateHeroSection(isMobile) {
    const wrapper = document.querySelector("[data-hero-anime]") || document;
    const tl = gsap.timeline();

    // Ajustes para mobile
    const mobileDurationMultiplier = isMobile ? 0.7 : 1;
    const mobileStaggerMultiplier = isMobile ? 0.5 : 1;

    // Hero blur animation
