                    segurança para impedir acessos não autorizados aos seus sistemas; (b) gerenciamento rigoroso do acesso às
                    informações recolhidas, assegurado pela adesão estrita dos funcionários e colaboradores externos aos termos
                    de confidencialidade, com ações guiadas pelos princípios de proporcionalidade, necessidade e relevância,
                    sempre com o intuito de salvaguardar a privacidade conforme estabelecido nesta Política; (c) treinamentos
                    periódicos e contínuos de seus colaboradores, destinados a identificar, avaliar e mitigar riscos
                    relacionados à privacidade de dados e sobre as melhores práticas de proteção de dados e privacidade.</p>

                <h3>4.3.</h3>
