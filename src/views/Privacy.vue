                <p>Para aprimorar e otimizar suas campanhas publicitárias, a WETRACKR coleta dados dos anúncios veiculados a
                    gerenciadores de anúncios vinculados e/ou integração à Plataforma pelo Usuário, permitindo à WETRACKR
                    acessar as métricas relevantes das suas respectivas campanhas.</p>

