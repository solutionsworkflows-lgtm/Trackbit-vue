                <h3>3.1.</h3>
                <p>Salvo nas condições expressamente estabelecidas, a WETRACKR, atuando como Controladora dos dados, assegura
                    que os dados coletados através da Plataforma WETRACKR serão removidos de forma automática após sua
                    utilização para os propósitos identificados nesta Política de Privacidade.</p>

                <h3>3.2.</h3>
                <p>Os Usuários devem estar cientes de que a remoção de dados indispensáveis para a administração de suas contas
                    na Plataforma WETRACKR resultará na desativação de seu registro e na consequente interrupção dos serviços
                    prestados pela plataforma.</p>

                <h3>3.3.</h3>
                <p>Em situações onde a conta seja finalizada, decorrente da rescisão do Termo de Condições de Uso da Plataforma
                    WETRACKR, a WETRACKR se compromete a excluir do seu Banco de Dados os Dados associados à conta encerrada,
                    bem como quaisquer Dados fornecidos pelo cliente na Plataforma, isso ocorrerá após um período de 60 dias
                    contados a partir do término do contrato. Contudo, reteremos somente aqueles dados que forem imprescindíveis
                    para cumprir obrigações jurídicas da WETRACKR, cumprir regulamentações, resolver desacordos com o Usuário,
                    prevenir fraudes ou mau uso da Plataforma e dos Dados, e assegurar a aderência às disposições desta Política
                    de Privacidade e do Termo de Condições de Uso da Plataforma WETRACKR.</p>

                <h2>4. SEGURANÇA DE DADOS E COMPARTILHAMENTO</h2>

                <h3>4.1.</h3>
                <p>Todos os dados tratados pela WETRACKR são assegurados com a implementação de protocolos de segurança e
