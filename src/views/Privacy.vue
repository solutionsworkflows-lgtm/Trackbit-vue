                <h3>2.1.</h3>
                <p>Conforme dispõe o art. 18 da Lei Geral de Proteção de Dados (LGPD), pessoas físicas, enquanto titulares de
                    dados pessoais, possuem o direito de (a) confirmação da existência de tratamento de seus dados pessoais; (b)
                    acesso aos seus respectivos dados; (c) solicitar e receber a correção de dados incompletos, inexatos ou
                    desatualizados; (d) anonimização, bloqueio ou eliminação de dados desnecessários, excessivos ou tratados em
                    desconformidade com o disposto nesta Lei; (d) portabilidade dos dados a outro fornecedor de serviço ou
                    produto, mediante requisição expressa, de acordo com a regulamentação da autoridade nacional, observados os
                    segredos comercial e industrial; (e) eliminação dos dados pessoais tratados com o consentimento do titular,
                    exceto nas hipóteses previstas no art. 16 da Lei Geral de Proteção de Dados; (f) informação das entidades
                    públicas e privadas com as quais o controlador realizou uso compartilhado de dados; (g) informação sobre a
                    possibilidade de não fornecer consentimento e sobre as consequências da negativa; (h) revogação do
                    consentimento dado para o tratamento de dados, nos termos do § 5º do art. 8º da Lei Geral de Proteção de
                    Dados; (i) peticionar em relação aos seus dados contra o controlador perante a autoridade nacional de
                    proteção de dados; (j) opor-se a tratamento realizado com fundamento em uma das hipóteses de dispensa de
                    consentimento, em caso de descumprimento ao disposto na Lei Geral de Proteção de Dados; (k) exercer seus
                    direitos mediante requerimento expresso do titular ou de representante legalmente constituído, a agente de
                    tratamento, sendo atendido sem custos, nos prazos e nos termos previstos em regulamento.</p>

                <h3>2.2.</h3>
                <p>Caso o Titular procure exercer qualquer de seus direitos frente à WETRACKR, deverá comunica-la, por meio do
                    Encarregado de Proteção de Dados, conforme disposto nesta Política de Privacidade, a respeito de sua
                    requisição.</p>

                <h3>2.3.</h3>
                <p>A WETRACKR compromete-se a responder, em até 2 (dois) dias úteis, o Titular de Dados, quanto à sua
                    requisição, atendendo-a solicitação sempre que possível de maneira imediata, ou informando o prazo para
                    atendimento da solicitação.</p>

