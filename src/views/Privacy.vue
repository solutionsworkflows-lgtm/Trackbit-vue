                <p>Para usuários que optam por realizar a assinatura de planos pagos, os dados requeridos relacionados à
                    cobrança (dados de cartão de crédito e endereço de cobrança) não são armazenados pela WETRACKR.</p>

                <h3>1.3.</h3>
                <p>A Plataforma armazena dados de métricas vitais para a análise e otimização do desempenho das campanhas de
                    seus respectivos Usuários, isso inclui, mas não se limita a, dados e gastos com anúncios em Plataformas de
                    Gerenciadores de Anúncios, bem como nas vendas realizadas nas plataformas de vendas onde o compartilhamento
                    de dados e realizado pelo Usuário.</p>

                <h3>1.4.</h3>
                <p>Em virtude de sua atividade, a WETRACKR atua como Operadora de Dados, no que toca aos Dados de Terceiros
                    coletados pelo Usuário (através de outras plataformas, tais como Meta e/ou Google), sendo referidos dados
                    comunicados à Plataforma WETRACKR automaticamente pelos sistemas de webhooks e API's de sistema vinculados
                    pelo próprio Usuário. Isso significa que a WETRACKR tratará referidos Dados Pessoais por conta e ordem do
                    Usuário, ou seja, do titular da conta na WETRACKR, o qual figurará neste caso como o Controlador de Dados,
                    responsável por tais operações de tratamento. Desse modo, é de responsabilidade do Usuário, em conformidade
                    com o disposto na Lei n° 13.709/18, estipular os objetivos que justificam a realização do Tratamento, sua
                    respectiva base legal, bem como obter autorizações aplicáveis, cabendo ao mesmo atender às solicitações dos
                    Titulares de Dados Pessoais.</p>

                <h3>1.5.</h3>
                <p>Em atenção a segurança e privacidade dos dados, a WETRACKR não coleta, recebe ou mantém em guarda dados
                    sensíveis dos Usuários ou de terceiros. Caso tais dados sejam recebidos inadvertidamente de plataformas
                    terceiras, eles são imediatamente excluídos, tão logo sejam identificados, assegurando que não sejam
                    armazenados ou compartilhados com terceiros.</p>

